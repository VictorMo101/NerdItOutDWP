DROP DATABASE IF EXISTS nioDB;
CREATE DATABASE nioDB CHARACTER SET utf8mb4 COLLATE utf8mb4_bin;
USE nioDB;

CREATE TABLE Users (
    userID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(80) NOT NULL UNIQUE,
    password VARCHAR(100) NOT NULL,
    displayName VARCHAR(80) NOT NULL,
    bio VARCHAR(500), 
    avatar VARCHAR(2048),
    coinsBalance INT NOT NULL DEFAULT 0,
    coinsRefillDate DATE,
    isAdmin BOOLEAN DEFAULT FALSE
);

CREATE TABLE Posts (
    postID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    userID INT NOT NULL,
    text VARCHAR(280) NOT NULL,
    createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    image VARCHAR(2048),
    FOREIGN KEY (userID) REFERENCES Users (userID) ON DELETE CASCADE
);

CREATE TABLE Comments (
    commentID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    userID INT NOT NULL,
    postID INT NOT NULL,
    text VARCHAR(280) NOT NULL,
    FOREIGN KEY (userID) REFERENCES Users (userID) ON DELETE CASCADE,
    FOREIGN KEY (postID) REFERENCES Posts (postID) ON DELETE CASCADE
);

CREATE TABLE Likes (
    userID INT NOT NULL,
    postID INT NOT NULL,
    PRIMARY KEY (userID, postID),
    FOREIGN KEY (userID) REFERENCES Users (userID) ON DELETE CASCADE,
    FOREIGN KEY (postID) REFERENCES Posts (postID) ON DELETE CASCADE
);

CREATE TABLE CoinGifts (
    userID INT NOT NULL,
    postID INT NOT NULL,
    amount INT NOT NULL,
    PRIMARY KEY (userID, postID),
    FOREIGN KEY (userID) REFERENCES Users (userID) ON DELETE CASCADE,
    FOREIGN KEY (postID) REFERENCES Posts (postID) ON DELETE CASCADE
);

CREATE TABLE Follows (
    followerID INT NOT NULL,
    followedID INT NOT NULL,
    PRIMARY KEY (followerID, followedID),
    FOREIGN KEY (followerID) REFERENCES Users (userID) ON DELETE CASCADE,
    FOREIGN KEY (followedID) REFERENCES Users (userID) ON DELETE CASCADE
);

CREATE TABLE ReportStatuses (
    statusID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(20) NOT NULL UNIQUE
);

INSERT INTO ReportStatuses (name) VALUES ('open'), ('approved'), ('disapproved');

CREATE TABLE Reports (
    reportID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    reporterID INT NOT NULL,
    postID INT NOT NULL,
    text VARCHAR(280),
    statusID INT NOT NULL DEFAULT 1,
    createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (reporterID, postID),
    FOREIGN KEY (reporterID) REFERENCES Users (userID) ON DELETE CASCADE,
    FOREIGN KEY (postID) REFERENCES Posts (postID) ON DELETE CASCADE,
    FOREIGN KEY (statusID) REFERENCES ReportStatuses (statusID)
);